// Schema changes after the base schema (db/schema.pg.sql, version 1). lib/db.ts applies the ones a database
// hasn't had yet, in order, on first use after a deploy. Each must be safe to run on any database at the
// previous version. Never edit one that has shipped; add a new one.
export const MIGRATIONS: { version: number; sql: string }[] = [
  {
    version: 2,
    // Phones signed in to the FerriDash app: where to send push notifications for each user.
    sql: `
      CREATE TABLE IF NOT EXISTS push_devices (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        token TEXT NOT NULL UNIQUE,
        platform TEXT NOT NULL CHECK (platform IN ('android','ios')),
        created_at TEXT NOT NULL DEFAULT (ferri_now()),
        last_seen_at TEXT NOT NULL DEFAULT (ferri_now())
      );
      CREATE INDEX IF NOT EXISTS idx_push_devices_user ON push_devices(user_id);
      ALTER TABLE push_devices ENABLE ROW LEVEL SECURITY;`,
  },
  {
    version: 3,
    // A document or picture attached to a message (the file itself is in storage, under attachment_key).
    sql: `
      ALTER TABLE messages ADD COLUMN IF NOT EXISTS attachment_key TEXT;
      ALTER TABLE messages ADD COLUMN IF NOT EXISTS attachment_name TEXT;
      ALTER TABLE messages ADD COLUMN IF NOT EXISTS attachment_type TEXT;
      ALTER TABLE messages ADD COLUMN IF NOT EXISTS attachment_size INTEGER;`,
  },
  {
    version: 4,
    // Assignments set for a class's subject (the optional PDF is in storage, assignment-docs/<id>.pdf),
    // and when each learner or parent last opened the assignments page (for the top bar's dot).
    sql: `
      CREATE TABLE IF NOT EXISTS assignments (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        school_id INTEGER NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
        class_subject_id INTEGER NOT NULL REFERENCES class_subjects(id) ON DELETE CASCADE,
        title TEXT NOT NULL,
        instructions TEXT,
        due_date TEXT NOT NULL,
        document_name TEXT,
        created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
        created_at TEXT NOT NULL DEFAULT (ferri_now())
      );
      CREATE INDEX IF NOT EXISTS idx_assignments_cs ON assignments(class_subject_id, due_date);
      CREATE INDEX IF NOT EXISTS idx_assignments_school ON assignments(school_id, due_date);
      ALTER TABLE assignments ENABLE ROW LEVEL SECURITY;
      ALTER TABLE users ADD COLUMN IF NOT EXISTS assignments_seen_at TEXT;`,
  },
  {
    version: 5,
    // A banner (cover) picture on each user's profile and dashboard (the image is in storage, banners/<id>.img).
    sql: `ALTER TABLE users ADD COLUMN IF NOT EXISTS banner_updated_at TEXT;`,
  },
  {
    version: 6,
    // Each user's interface language (lib/i18n: en, af, zu, xh, nr, nso, st, tn, ss, ve, ts). Null means English.
    sql: `ALTER TABLE users ADD COLUMN IF NOT EXISTS language TEXT;`,
  },
];
