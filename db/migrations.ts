// Schema changes after the base schema (db/schema.pg.sql, version 1). lib/db.ts applies the ones a database
// hasn't had yet, in order, on first use after a deploy. Each must be safe to run on any database at the
// previous version. Never edit one that has shipped; add a new one.
export const MIGRATIONS: { version: number; sql: string }[] = [
  {
    version: 2,
    // Phones signed in to the FerriDash app: where to send push notifications for each user.
    sql: `
      CREATE TABLE IF NOT EXISTS push_devices (
        id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        token TEXT NOT NULL UNIQUE,
        platform TEXT NOT NULL CHECK (platform IN ('android','ios')),
        created_at TEXT NOT NULL DEFAULT (ferri_now()),
        last_seen_at TEXT NOT NULL DEFAULT (ferri_now())
      );
      CREATE INDEX IF NOT EXISTS idx_push_devices_user ON push_devices(user_id);
      ALTER TABLE push_devices ENABLE ROW LEVEL SECURITY;`,
  },
];
